#!/usr/bin/env python3
"""Deterministic sample generation for datasets/samples (stdlib only).

Owner: dataset-engineer.

Real records only. This script copies or field-projects records that were
obtained from official sources; it never invents values. Synthetic edge-case
files (names containing 'synthetic') are hand-written and not produced here.

Subcommands
  dblp        Copy the records listed in selection.json (dblp.keys) verbatim
              from a local DBLP XML file (plain or .gz; a truncated bounded
              prefix from download_dblp.sh is fine; the default 16 MiB prefix
              contains every selected key) into a standalone sample
              whose internal DTD subset declares only the entities it uses
              (definitions copied from the official dblp.dtd).
  enrichment  Build OpenAlex/Crossref/ORCID JSONL samples from the response
              cache written by fetch_enrichment.py sample-set.

Idempotent: outputs are rewritten only when their content changes.

Usage
  make_samples.py dblp --input DBLP.xml[.gz] --dtd dblp.dtd [--out PATH]
  make_samples.py enrichment --cache DIR [--out-dir datasets/samples]
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import re
import sys
import zlib

sys.dont_write_bytecode = True  # keep datasets/scripts free of __pycache__
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dslib  # noqa: E402

SAMPLES_DIR = os.path.join(dslib.DATASETS_DIR, "samples")
SELECTION = os.path.join(SAMPLES_DIR, "selection.json")
RECORD_TAGS = "article|inproceedings|proceedings|book|incollection|phdthesis|mastersthesis|www|data"
MAX_INPUT_BYTES = 512 * 1024 * 1024  # decompressed bytes scanned at most


def write_if_changed(path: str, data: bytes) -> None:
    if os.path.exists(path):
        with open(path, "rb") as fh:
            if fh.read() == data:
                print("unchanged: %s" % path)
                return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "wb") as fh:
        fh.write(data)
    os.replace(tmp, path)
    print("wrote: %s (%d bytes)" % (path, len(data)))


def read_dblp_text(path: str, wanted: set) -> str:
    """Read (possibly truncated) DBLP XML; stop once all wanted keys are seen."""
    buf = []
    total = 0
    found = set()
    key_re = re.compile(r'key="([^"]+)"')
    if dslib.is_gzip(path):
        d = zlib.decompressobj(16 + zlib.MAX_WBITS)
        with open(path, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                try:
                    out = d.decompress(chunk)
                except zlib.error:
                    break
                text = out.decode("latin-1")
                buf.append(text)
                total += len(out)
                found.update(k for k in key_re.findall(text) if k in wanted)
                if found >= wanted or total > MAX_INPUT_BYTES:
                    break
    else:
        with open(path, "rb") as fh:
            while total <= MAX_INPUT_BYTES:
                out = fh.read(1 << 20)
                if not out:
                    break
                text = out.decode("latin-1")
                buf.append(text)
                total += len(out)
                found.update(k for k in key_re.findall(text) if k in wanted)
                if found >= wanted:
                    # read a little more so the last record is complete
                    buf.append(fh.read(1 << 16).decode("latin-1"))
                    break
    return "".join(buf)


def cmd_dblp(a) -> int:
    with open(SELECTION, encoding="utf-8") as fh:
        sel = json.load(fh)
    keys = sel["dblp"]["keys"]
    text = read_dblp_text(a.input, set(keys))
    with open(a.dtd, encoding="latin-1") as fh:
        entities = dslib.dtd_general_entities(fh.read())
    records = []
    for k in keys:
        m = re.search(r'<(%s)\s[^>]*key="%s"[^>]*>.*?</\1>' % (RECORD_TAGS, re.escape(k)), text, re.S)
        if not m:
            print("missing key in input: %s" % k, file=sys.stderr)
            return 1
        records.append(m.group(0))
    used = sorted(set(re.findall(r"&([A-Za-z][A-Za-z0-9]*);", "\n".join(records))) - {"amp", "lt", "gt", "quot", "apos"})
    missing = [e for e in used if e not in entities]
    if missing:
        print("entities not defined in DTD: %s" % missing, file=sys.stderr)
        return 1
    header = (
        '<?xml version="1.0" encoding="ISO-8859-1"?>\n'
        "<!--\n"
        "  ScholarChain DBLP sample (REAL records, copied verbatim).\n"
        "  Source: dblp computer science bibliography, monthly snapshot release\n"
        "  %s (DOI 10.4230/dblp.xml.2026-11-01), https://dblp.org\n"
        "  License: CC0 1.0 (https://creativecommons.org/publicdomain/zero/1.0/).\n"
        "  Generated by datasets/scripts/make_samples.py dblp. The internal DTD subset\n"
        "  declares only the entities used below, copied from https://dblp.org/xml/dblp.dtd;\n"
        "  the real dump instead references the external DTD.\n"
        "-->\n" % sel["dblp"]["source_release"]
    )
    decls = "".join('<!ENTITY %s "%s">\n' % (e, entities[e]) for e in used)
    body = "<!DOCTYPE dblp [\n%s]>\n<dblp>\n%s\n</dblp>\n" % (decls, "\n".join(records))
    write_if_changed(a.out, (header + body).encode("latin-1"))
    return 0


def load_cached(cache: str, source: str) -> list:
    out = []
    for p in sorted(glob.glob(os.path.join(cache, source, "*.json"))):
        with open(p, encoding="utf-8") as fh:
            out.append(json.load(fh))
    return out


def jsonl(records: list) -> bytes:
    return "".join(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n" for r in records).encode("utf-8")


def project_orcid(person: dict, works: dict, keep_dois: set) -> dict:
    name = person.get("name") or {}

    def val(x):
        return (x or {}).get("value") if isinstance(x, dict) else None

    groups = []
    for g in works.get("group", []):
        ext = g.get("external-ids", {}).get("external-id", [])
        dois = {dslib.normalize_doi(e.get("external-id-value")) for e in ext if e.get("external-id-type") == "doi"}
        if not (dois & keep_dois):
            continue
        summaries = []
        for s in g.get("work-summary", []):
            summaries.append({
                "put-code": s.get("put-code"),
                "type": s.get("type"),
                "title": val((s.get("title") or {}).get("title")),
                "publication-date": s.get("publication-date"),
                "external-ids": s.get("external-ids"),
                "source-name": val((s.get("source") or {}).get("source-name")),
            })
        groups.append({"external-ids": g.get("external-ids"), "work-summary": summaries})
    groups.sort(key=lambda g: json.dumps(g["external-ids"], sort_keys=True))
    return {
        "orcid-path": name.get("path"),
        "name": {
            "given-names": val(name.get("given-names")),
            "family-name": val(name.get("family-name")),
            "credit-name": val(name.get("credit-name")),
            "visibility": name.get("visibility"),
        },
        "works-group-projection": groups,
        "_projection": "ScholarChain field projection of ORCID Public API v3.0 /person and /works; "
                       "biography, emails, addresses, keywords, researcher-urls, other external "
                       "identifiers and all non-selected works were dropped.",
    }


def cmd_enrichment(a) -> int:
    with open(SELECTION, encoding="utf-8") as fh:
        sel = json.load(fh)
    out_dir = a.out_dir
    # OpenAlex works and authors share the 'openalex' cache.
    works, authors = {}, {}
    for resp in load_cached(a.cache, "openalex"):
        for r in resp.get("results", [resp] if "id" in resp else []):
            rid = r.get("id", "")
            if "/W" in rid:
                works[rid] = r
            elif "/A" in rid:
                authors[rid] = r
    want_w = {dslib.normalize_doi(d) for d in sel["openalex_works"]["dois"]}
    w_out = [works[k] for k in sorted(works) if dslib.normalize_doi(works[k].get("doi")) in want_w]
    want_a = {dslib.normalize_openalex_id(i, "author") for i in sel["openalex_authors"]["ids"]}
    a_out = [authors[k] for k in sorted(authors) if dslib.normalize_openalex_id(k, "author") in want_a]
    cr = {}
    for resp in load_cached(a.cache, "crossref"):
        msg = resp.get("message", {})
        for item in msg.get("items", [msg] if "DOI" in msg else []):
            cr[dslib.normalize_doi(item["DOI"])] = item
    want_c = [dslib.normalize_doi(d) for d in sel["crossref_works"]["dois"]]
    c_out = [cr[d] for d in sorted(want_c) if d in cr]
    persons, workss = {}, {}
    for resp in load_cached(a.cache, "orcid"):
        m = re.search(r"[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{3}[0-9X]", str(resp.get("path", "")))
        if not m:
            continue
        if "name" in resp:
            persons[m.group(0)] = resp
        elif "group" in resp:
            workss[m.group(0)] = resp
    keep = {dslib.normalize_doi(d) for d in sel["orcid"]["keep_work_dois"]}
    o_out = []
    for o in sel["orcid"]["orcids"]:
        p = persons.get(dslib.normalize_orcid(o))
        w = workss.get(dslib.normalize_orcid(o))
        if p is None or w is None:
            print("missing ORCID cache for %s" % o, file=sys.stderr)
            return 1
        o_out.append(project_orcid(p, w, keep))
    counts = {"openalex works": (len(w_out), len(want_w)), "openalex authors": (len(a_out), len(want_a)),
              "crossref works": (len(c_out), len(want_c)), "orcid records": (len(o_out), len(sel["orcid"]["orcids"]))}
    for k, (got, want) in counts.items():
        if got != want:
            print("incomplete %s: %d of %d" % (k, got, want), file=sys.stderr)
            return 1
    write_if_changed(os.path.join(out_dir, "openalex", "works.jsonl"), jsonl(w_out))
    write_if_changed(os.path.join(out_dir, "openalex", "authors.jsonl"), jsonl(a_out))
    write_if_changed(os.path.join(out_dir, "crossref", "works.jsonl"), jsonl(c_out))
    write_if_changed(os.path.join(out_dir, "orcid", "records.jsonl"), jsonl(o_out))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("dblp")
    d.add_argument("--input", required=True)
    d.add_argument("--dtd", required=True)
    d.add_argument("--out", default=os.path.join(SAMPLES_DIR, "dblp", "dblp-sample.xml"))
    e = sub.add_parser("enrichment")
    e.add_argument("--cache", required=True)
    e.add_argument("--out-dir", default=SAMPLES_DIR)
    a = ap.parse_args()
    return cmd_dblp(a) if a.cmd == "dblp" else cmd_enrichment(a)


if __name__ == "__main__":
    sys.exit(main())
